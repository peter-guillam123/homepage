// The first tag on a piece that names a place. Section fallbacks come last.
const HOME = new Set(['uk-news', 'us-news', 'australia-news']);
export function placeOf(tagIds = [], sectionId = null) {
  if (sectionId && HOME.has(sectionId)) {
    const nation = tagIds.find(id => id.startsWith('uk/') && PLACES[id]);
    return nation || sectionId;
  }
  const scope = ['world', 'global-development'].includes(sectionId) ? tagIds : tagIds.slice(0, 3);
  for (const id of scope) if (PLACES[id] && !HOME.has(id)) return id;
  return null;
}
